func TestSplitCSV(t *testing.T) {
	cases := []struct {
		input    string
		expected []string
	}{
		{"", nil},
		{"  ", nil},
		{".go", []string{".go"}},
		{".go,.py,.ts", []string{".go", ".py", ".ts"}},
		{".go, .py , .ts", []string{".go", ".py", ".ts"}},
		{",,", nil},
	}
	for _, tc := range cases {
		got := splitCSV(tc.input)
		if len(got) != len(tc.expected) {
			t.Errorf("splitCSV(%q) = %v, want %v", tc.input, got, tc.expected)

			continue
		}

		for i := range got {
			if got[i] != tc.expected[i] {
				t.Errorf("splitCSV(%q)[%d] = %q, want %q", tc.input, i, got[i], tc.expected[i])
			}
		}
	}
}

func TestHasAuthor(t *testing.T) {
	names := []string{"Alice", "Bob", "Carol"}
	if !hasAuthor(names, "Alice") {
		t.Error("hasAuthor should find Alice")
	}

	if !hasAuthor(names, "alice") {
		t.Error("hasAuthor should be case-insensitive")
	}

	if hasAuthor(names, "Dave") {
		t.Error("hasAuthor should not find Dave")
	}

	if hasAuthor(nil, "Alice") {
		t.Error("hasAuthor should return false for nil slice")
	}
}

func TestRunVersion(t *testing.T) {
	var buf bytes.Buffer

	err := run([]string{"--version"}, &buf, io.Discard, time.Now())
	if err != nil {
		t.Fatalf("run --version returned error: %v", err)
	}

	out := buf.String()
	if !strings.Contains(out, "go-hotspot version") {
		t.Errorf("version output missing header, got: %q", out)
	}
}
